const langs = { ko, en }

const SETTINGS_KEY = 'commute.language.v1'

let currentLang = localStorage.getItem(SETTINGS_KEY) || (navigator.language?.startsWith('ko') ? 'ko' : 'en')

export function setLanguage(lang) {
  currentLang = lang
  localStorage.setItem(SETTINGS_KEY, lang)
}

export function getLanguage() {
  return currentLang
}

export function t(key) {
  return langs[currentLang]?.[key] || langs.en[key] || key
}

export function getDayLabel(dayId) {
  const days = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat']
  return t(days[dayId]) || days[dayId]
}
